"""Render ml/reports/run_record.md from a training run (numbers are never typed by hand)."""

from __future__ import annotations

from typing import Any

LABELS = {
    "dummy_prior": "Dummy (prior)",
    "logistic_regression": "Logistic regression",
    "gradient_boosting": "Gradient boosting",
}


def _ci(m: dict[str, float], digits: int = 3) -> str:
    return f"{m['estimate']:.{digits}f} [{m['ci_low']:.{digits}f}, {m['ci_high']:.{digits}f}]"


def render_run_record(result: dict[str, Any], meta: dict[str, Any]) -> str:
    d = result["data"]
    lines = [
        "# Early-warning model — run record",
        "",
        "Generated by `python -m edupulse_ml.train`. Do not edit by hand.",
        "",
        f"- Trained: {meta['trained_at']} · model version {meta['model_version']} · "
        f"scikit-learn {meta['scikit_learn']}",
        f"- Data: UCI Student Performance (DOI {d['doi']}, {d['licence']}); {d['rows']} rows "
        f"(maths + Portuguese), {d['students_groups']} student groups; "
        f"{d['positives']} fails ({d['prevalence']:.1%}).",
        f"- Split: {d['train_rows']} train / {d['test_rows']} test rows "
        f"({d['test_positives']} test positives), grouped by student.",
        f"- Prediction moment: {result['protocol']['prediction_moment']}.",
        f"- Target: {result['protocol']['target']}.",
        f"- Features: {', '.join(f['name'] for f in d['features'])}.",
        f"- Chosen model: **{LABELS[result['chosen_model']]}** "
        f"({result['protocol']['selection_rule']}).",
        f"- Model file SHA-256: `{meta['model_sha256']}`",
        "",
        f"## Cross-validation ({result['protocol']['cv']}, training part only)",
        "",
        "| Model | Average precision | ROC AUC | Brier |",
        "|---|---|---|---|",
    ]
    for name, summary in result["cv"].items():
        cells = [
            f"{summary[k]['mean']:.3f} ± {summary[k]['sd']:.3f}"
            for k in ("average_precision", "roc_auc", "brier")
        ]
        lines.append(f"| {LABELS[name]} | " + " | ".join(cells) + " |")

    t = result["thresholds"]
    o = t["out_of_fold_at_high"]
    lines += [
        "",
        "## Operating threshold (chosen on out-of-fold predictions only)",
        "",
        f"- High-risk band: probability ≥ **{t['high']:.3f}** "
        f"({result['protocol']['threshold_rule']}).",
        f"- Medium band: probability ≥ {t['medium']:.3f} (95 % out-of-fold recall).",
        f"- Out-of-fold at the high threshold: precision {o['precision']:.3f}, "
        f"recall {o['recall']:.3f}, flag rate {o['flag_rate']:.3f}.",
        "",
        f"## Held-out test set (scored once; {result['protocol']['bootstrap']})",
        "",
        "Threshold-based columns use the chosen model's operating threshold *t* for every row.",
        "",
        "| Model | Average precision | ROC AUC | Brier | Precision @ t | Recall @ t | F1 @ t |",
        "|---|---|---|---|---|---|---|",
    ]
    for name, m in result["test"].items():
        keys = ("average_precision", "roc_auc", "brier", "precision", "recall", "f1")
        lines.append(f"| {LABELS[name]} | " + " | ".join(_ci(m[k]) for k in keys) + " |")

    lines += [
        "",
        "## Fairness check by sex (chosen model, high threshold)",
        "",
        "Sex is not a model input; it is used here only to compare error rates. With these group",
        "sizes the result is **inconclusive and is not evidence of fairness**.",
        "",
        "| Set | Group | n | Positives | Recall | Precision | Flag rate |",
        "|---|---|---|---|---|---|---|",
    ]
    for set_name, report in result["fairness_by_sex"].items():
        for group in ("F", "M"):
            r = report[group]
            lines.append(
                f"| {set_name} | {group} | {r['n']} | {r['positives']} | {_ci(r['recall'])} | "
                f"{_ci(r['precision'])} | {_ci(r['flag_rate'])} |"
            )
        gap = report["gap_F_minus_M"]
        lines.append(
            f"| {set_name} | gap F-M | | | {gap['recall']:+.3f} | {gap['precision']:+.3f} "
            f"| {gap['flag_rate']:+.3f} |"
        )

    sa = result.get("split_audit")
    if sa:
        lines += [
            "",
            "## Split audit (students in both course files)",
            "",
            f"- Identity attributes used for matching: {len(sa['identity_attributes'])}.",
            f"- Rows produced by the dataset documentation's merge on them: "
            f"{sa['documented_merge_rows']}.",
            f"- Identity groups: {sa['groups']}; groups with rows in both files: "
            f"{sa['groups_in_both_files']} ({sa['both_file_groups_in_test']} in the test set); "
            f"groups with more than two rows (attribute collisions, kept together): "
            f"{sa['groups_with_more_than_two_rows']}.",
            f"- Groups on both sides of the holdout: **{sa['groups_crossing_holdout']}**; "
            f"on both sides of any CV fold: **{max(sa['groups_crossing_cv_folds'])}** "
            f"(checked for all {len(sa['groups_crossing_cv_folds'])} folds).",
        ]
    log = result.get("test_scoring_log")
    if log:
        lines += ["", "Holdout access log: " + " → ".join(log) + "."]

    pre = result.get("pre_term_variant")
    if pre:
        t = pre["test"]
        lines += [
            "",
            "## Pre-term variant (no period grades)",
            "",
            f"Same model family, inputs {', '.join(pre['features'])}; own threshold "
            f"{pre['threshold_high']:.3f} (80 % out-of-fold recall); test scored once.",
            "",
            "| Model | CV average precision | Test AP | Test ROC AUC "
            "| Precision @ t | Recall @ t |",
            "|---|---|---|---|---|---|",
            f"| After first-period grades (deployed) | "
            f"{result['cv'][result['chosen_model']]['average_precision']['mean']:.3f} ± "
            f"{result['cv'][result['chosen_model']]['average_precision']['sd']:.3f} | "
            + " | ".join(
                _ci(result["test"][result["chosen_model"]][k])
                for k in ("average_precision", "roc_auc", "precision", "recall")
            )
            + " |",
            f"| Pre-term (no grades) | {pre['cv']['average_precision']['mean']:.3f} ± "
            f"{pre['cv']['average_precision']['sd']:.3f} | "
            + " | ".join(_ci(t[k]) for k in ("average_precision", "roc_auc", "precision", "recall"))
            + " |",
        ]

    imp = result.get("permutation_importance_test")
    if imp:
        lines += [
            "",
            "## Permutation importance on the test set (deployed model; descriptive only)",
            "",
            "| Feature | Mean drop in AP | SD | Share | Computable by EduPulse |",
            "|---|---|---|---|---|",
        ]
        for name, m in imp.items():
            lines.append(
                f"| {name} | {m['mean_ap_drop']:.3f} | {m['sd']:.3f} | {m['share']:.1%} | "
                f"{'yes' if m['app_computable'] else 'no'} |"
            )

    lines += [
        "",
        "## Ablations (CV average precision, chosen model family)",
        "",
        "| Feature set | Average precision |",
        "|---|---|",
    ]
    for label, m in result["ablations_cv_average_precision"].items():
        lines.append(f"| {label} | {m['mean']:.3f} ± {m['sd']:.3f} |")

    if result.get("coefficients"):
        lines += [
            "",
            "## Coefficients (log-odds per standard deviation)",
            "",
            "| Feature | Coefficient | Mean | SD |",
            "|---|---|---|---|",
        ]
        for name, c in result["coefficients"].items():
            lines.append(f"| {name} | {c['coef_per_sd']:+.3f} | {c['mean']:.2f} | {c['sd']:.2f} |")

    env = result["environment"]
    lines += [
        "",
        "## Environment",
        "",
        f"Python {env['python']}, scikit-learn {env['scikit_learn']}, "
        f"numpy {env['numpy']}, pandas {env['pandas']}.",
        "",
    ]
    return "\n".join(lines)

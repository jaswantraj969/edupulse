"""Write docs/process/REVIEW_BUNDLE*.md: the verbatim source a reviewer asked to read in one place.

Usage::

    python scripts/make_review_bundle.py

The bundle is git-ignored (it duplicates committed files). It starts with the commit hash and a
file list with line counts and is split into _1, _2, ... parts above 400,000 characters.
"""

from __future__ import annotations

import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT_DIR = ROOT / "docs" / "process"
LIMIT = 400_000

SECTIONS: list[tuple[str, list[str]]] = [
    (
        "Backend: authentication, tokens, passwords, rate limiting, settings",
        [
            "backend/app/core/config.py",
            "backend/app/core/security.py",
            "backend/app/core/passwords.py",
            "backend/app/core/rate_limit.py",
            "backend/app/models/auth.py",
            "backend/app/services/auth.py",
            "backend/app/api/routes/auth.py",
            "backend/app/schemas/auth.py",
        ],
    ),
    (
        "Backend: role guards and teacher scoping",
        ["backend/app/api/deps.py", "backend/app/services/access.py"],
    ),
    (
        "Backend: CSV import/export",
        ["backend/app/services/csv_io.py", "backend/app/api/routes/students.py"],
    ),
    (
        "Backend: risk scoring service, route and schemas",
        [
            "backend/app/services/risk.py",
            "backend/app/api/routes/risk.py",
            "backend/app/schemas/risk.py",
        ],
    ),
    (
        "Backend: audit log",
        [
            "backend/app/models/audit.py",
            "backend/app/services/audit.py",
            "backend/app/api/routes/audit.py",
        ],
    ),
    (
        "Frontend: where tokens are held in the browser",
        ["frontend/src/lib/api.ts", "frontend/src/lib/auth.tsx"],
    ),
    (
        "ML: data loading, features/mapping, split, training and selection, threshold, "
        "final evaluation",
        [
            "ml/edupulse_ml/data.py",
            "ml/edupulse_ml/features.py",
            "ml/edupulse_ml/train.py",
            "ml/edupulse_ml/guard.py",
            "ml/edupulse_ml/evaluate.py",
            "ml/edupulse_ml/explain.py",
            "ml/edupulse_ml/export.py",
            "ml/edupulse_ml/reproduce.py",
        ],
    ),
    (
        "Tests: role boundaries, teacher scoping, CSV injection, tokens, ML split and holdout",
        [
            "backend/tests/conftest.py",
            "backend/tests/test_roles.py",
            "backend/tests/test_access.py",
            "backend/tests/test_students.py",
            "backend/tests/test_auth.py",
            "backend/tests/test_config.py",
            "backend/tests/test_seed.py",
            "backend/tests/test_csv.py",
            "backend/tests/test_audit.py",
            "backend/tests/test_risk.py",
            "frontend/src/lib/__tests__/api.test.ts",
            "ml/tests/test_pipeline.py",
            "ml/tests/test_train_end_to_end.py",
            "ml/tests/test_guard.py",
            "ml/tests/test_reproduce.py",
        ],
    ),
    ("Documentation", ["docs/model_card.md"]),
]
FENCE = {".py": "python", ".ts": "ts", ".tsx": "tsx", ".md": "markdown"}


def decisions_section() -> str:
    text = (ROOT / "docs/process/PROJECT_STATUS.md").read_text(encoding="utf-8")
    start = text.index("## Decisions")
    end = text.index("## Deviations and limitations")
    return text[start:end].rstrip() + "\n"


def block(title: str, body: str, lang: str) -> str:
    fence = "````" if "```" in body else "```"
    return f"### `{title}`\n\n{fence}{lang}\n{body.rstrip()}\n{fence}\n\n"


def main() -> None:
    commit = subprocess.run(
        ["git", "rev-parse", "HEAD"],  # noqa: S607 - fixed command
        cwd=ROOT,
        check=True,
        capture_output=True,
        text=True,
    ).stdout.strip()
    files = [path for _, paths in SECTIONS for path in paths]
    contents = {p: (ROOT / p).read_text(encoding="utf-8") for p in files}
    decisions = decisions_section()

    header = [
        "# EduPulse review bundle",
        "",
        f"Commit: `{commit}`",
        "",
        "Verbatim file contents (generated by `scripts/make_review_bundle.py`; not committed).",
        "",
        "| File | Lines |",
        "|---|---|",
    ]
    header += [f"| `{p}` | {len(contents[p].splitlines())} |" for p in files]
    header += [
        f"| `docs/process/PROJECT_STATUS.md` — Decisions section | {len(decisions.splitlines())} |",
        "",
    ]

    chunks = ["\n".join(header) + "\n"]
    for title, paths in SECTIONS:
        part = f"## {title}\n\n"
        for path in paths:
            part += block(path, contents[path], FENCE.get(Path(path).suffix, ""))
        chunks.append(part)
    chunks.append("## PROJECT_STATUS.md — Decisions\n\n" + decisions)

    parts: list[str] = [""]
    for chunk in chunks:
        if parts[-1] and len(parts[-1]) + len(chunk) > LIMIT:
            parts.append("")
        parts[-1] += chunk
    for old in OUT_DIR.glob("REVIEW_BUNDLE*.md"):
        old.unlink()
    names = (
        ["REVIEW_BUNDLE.md"]
        if len(parts) == 1
        else [f"REVIEW_BUNDLE_{i}.md" for i in range(1, len(parts) + 1)]
    )
    for name, text in zip(names, parts, strict=True):
        (OUT_DIR / name).write_text(text, encoding="utf-8")
        print(f"{name}: {len(text):,} characters")


if __name__ == "__main__":
    main()
